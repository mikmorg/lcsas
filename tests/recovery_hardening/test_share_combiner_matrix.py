"""The two share combiners give the same answer on every input (#955, #967 item 2).

The C ``lcsas-shares`` (built here from ``recovery/src/lcsas-keyshare``)
and the Python ``combine_shares.py`` (the META disc's fallback, over
``lcsas.keyshare``) are run as programs on the same inputs: real share
cards from ``lcsas password split``, typed the ways an heir types them.
Each row must give the same exit status, the password byte-exact on
success, and the same words in the error otherwise.

The inputs:

- #955: the card's words with their numbers (``1 change 2 marathon``,
  ``1. change``, ``1) change``), in rows of four as the new card prints
  them, in 4-letter prefixes, wrapped over lines, the old one-line card;
  a wrong word is reported by its number on the card.
- #967 item 2: ``LCSAS_SHARE_PASSPHRASE`` set, ``--passphrase X``, the
  retired ``LCSAS_KEYSHARE_PASSPHRASE``, a UTF-16 card file (what
  Windows PowerShell ``>`` writes), and a file that is not text at all.
- CRLF, tabs, a UTF-8 BOM, standard input.

The C program is built from source with the Makefile's CFLAGS into a
temporary folder, so this tests the source, not the committed binaries
(``recovery/bin``, regenerated by CI).  Skipped with no C compiler.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

from lcsas.cli.main import main as cli_main
from lcsas.keyshare import extract_mnemonic

REPO_ROOT = Path(__file__).resolve().parents[2]
COMBINE_PY = REPO_ROOT / "src" / "lcsas" / "meta" / "combine_shares.py"

#: A password long enough that a share has more than 40 words.
PASSWORD = b"correct horse battery staple, a long one: 0123456789"
#: A share word no card has.
TYPO = "zqzq"

pytestmark = pytest.mark.skipif(
    shutil.which("make") is None or shutil.which("cc") is None,
    reason="building lcsas-shares needs make and cc",
)


@pytest.fixture(scope="module")
def c_bin(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """lcsas-shares built from this checkout's source."""
    build = tmp_path_factory.mktemp("shares-build")
    target = build / "lcsas-shares"
    proc = subprocess.run(
        ["make", "-C", str(REPO_ROOT / "recovery"), "-s", f"BUILD={build}",
         str(target)],
        capture_output=True, text=True, timeout=600, check=False,
    )
    assert proc.returncode == 0 and target.is_file(), proc.stdout + proc.stderr
    return target


@pytest.fixture(scope="module")
def mnemonics(tmp_path_factory: pytest.TempPathFactory) -> list[str]:
    """The words of three cards of a 2-of-3 split, from the real
    ``lcsas password split``."""
    work = tmp_path_factory.mktemp("split")
    pw = work / "pw"
    pw.write_bytes(PASSWORD)
    out = work / "shares"
    assert cli_main([
        "password", "split", "--repo", "alpha", "--threshold", "2",
        "--shares", "3", "--password-file", str(pw), "--out", str(out),
        "--no-verify-repo",
    ]) == 0
    cards = sorted(out.glob("alpha-share-*-card.txt"))
    assert len(cards) == 3
    words = [extract_mnemonic(c.read_text(encoding="utf-8")) for c in cards]
    assert all(len(w.split()) > 40 for w in words)
    return words


class Run:
    def __init__(self, rc: int, out: bytes, err: str) -> None:
        self.rc, self.out, self.err = rc, out, err

    def __repr__(self) -> str:
        return f"exit {self.rc}, stdout {self.out!r}, stderr:\n{self.err}"


def _env(extra: dict[str, str] | None) -> dict[str, str]:
    env = {k: v for k, v in os.environ.items()
           if k not in ("LCSAS_SHARE_PASSPHRASE", "LCSAS_KEYSHARE_PASSPHRASE")}
    env["PYTHONPATH"] = str(REPO_ROOT / "src")
    env.update(extra or {})
    return env


def run(tool: str, c_bin: Path, args: list[str], stdin: bytes | None = None,
        env: dict[str, str] | None = None) -> Run:
    cmd = ([str(c_bin)] if tool == "c"
           else [sys.executable, str(COMBINE_PY)]) + args
    proc = subprocess.run(cmd, input=stdin if stdin is not None else b"",
                          capture_output=True, env=_env(env), timeout=60,
                          check=False)
    return Run(proc.returncode, proc.stdout, proc.stderr.decode("utf-8", "replace"))


def both(c_bin: Path, args: list[str], stdin: bytes | None = None,
         env: dict[str, str] | None = None) -> tuple[Run, Run]:
    return (run("c", c_bin, args, stdin, env), run("py", c_bin, args, stdin, env))


def old_card(words: str) -> str:
    """A card printed before #955: the words on one line."""
    return (
        "=============== LCSAS SHARE CARD ===============\n"
        "Backup set : alpha\nShare      : 1 of 3\n"
        "Split on   : 2026-01-01\nSplit ID   : 01234\n\n"
        "HOW TO USE IT\n  You need ANY 2 of the 3 shares to rebuild the\n\n"
        "THE SHARE WORDS (keep every word, in order)\n"
        f"  {words}\n\n"
        "  Tip: you may type just the first 4 letters of each word.\n"
        "================================================\n"
    )


def _write(path: Path, text: str | bytes) -> str:
    if isinstance(text, str):
        path.write_text(text, encoding="utf-8", newline="")
    else:
        path.write_bytes(text)
    return str(path)


def assert_password(c: Run, py: Run) -> None:
    assert c.rc == 0 and c.out == PASSWORD, f"C: {c}"
    assert py.rc == 0 and py.out == PASSWORD, f"Python: {py}"


def test_wrapped_lines_and_old_card(c_bin: Path, mnemonics: list[str],
                                    tmp_path: Path) -> None:
    """Old layouts still combine: words wrapped ten a line, and the old
    one-line card."""
    w = mnemonics[0].split()
    wrapped = "\n".join(" ".join(w[i:i + 10]) for i in range(0, len(w), 10))
    a = _write(tmp_path / "a.txt", wrapped + "\n")
    b = _write(tmp_path / "b.txt", old_card(mnemonics[1]))
    assert_password(*both(c_bin, [a, b]))


def test_stdin_one_share_a_line(c_bin: Path, mnemonics: list[str]) -> None:
    """The old stdin form: one share a line, lines next to each other."""
    piped = f"{mnemonics[0]}\n{mnemonics[1]}\n"
    assert_password(*both(c_bin, [], stdin=piped.encode()))


# ── #967 item 2: the four inputs the tools disagreed on ───────────────


def test_share_passphrase_variable_is_ignored(c_bin: Path, mnemonics: list[str],
                                              tmp_path: Path) -> None:
    """``lcsas password split`` makes no passphrase, so neither tool
    reads one: the variable changes nothing."""
    a = _write(tmp_path / "a.txt", mnemonics[0] + "\n")
    b = _write(tmp_path / "b.txt", mnemonics[1] + "\n")
    assert_password(*both(c_bin, [a, b], env={"LCSAS_SHARE_PASSPHRASE": "x"}))


def test_passphrase_option_is_unknown(c_bin: Path, mnemonics: list[str],
                                      tmp_path: Path) -> None:
    a = _write(tmp_path / "a.txt", mnemonics[0] + "\n")
    b = _write(tmp_path / "b.txt", mnemonics[1] + "\n")
    for r in both(c_bin, ["--passphrase", "x", a, b]):
        assert r.rc == 2 and r.out == b"", r
        assert "unknown option '--passphrase'" in r.err, r


def test_retired_passphrase_variable_is_refused(c_bin: Path, mnemonics: list[str],
                                                tmp_path: Path) -> None:
    a = _write(tmp_path / "a.txt", mnemonics[0] + "\n")
    b = _write(tmp_path / "b.txt", mnemonics[1] + "\n")
    for r in both(c_bin, [a, b], env={"LCSAS_KEYSHARE_PASSPHRASE": "x"}):
        assert r.rc == 2 and r.out == b"", r
        assert ("LCSAS_KEYSHARE_PASSPHRASE was renamed: use "
                "LCSAS_SHARE_PASSPHRASE") in r.err, r


def test_utf16_card_file(c_bin: Path, mnemonics: list[str], tmp_path: Path) -> None:
    """What Windows PowerShell's ``>`` writes: UTF-16 with a BOM, CRLF."""
    text = old_card(mnemonics[0]).replace("\n", "\r\n")
    a = _write(tmp_path / "a.txt", b"\xff\xfe" + text.encode("utf-16-le"))
    b = _write(tmp_path / "b.txt", b"\xfe\xff"
               + (mnemonics[1] + "\r\n").encode("utf-16-be"))
    assert_password(*both(c_bin, [a, b]))


def test_undecodable_file(c_bin: Path, mnemonics: list[str], tmp_path: Path) -> None:
    """A file that is not text: exit 3 and the same words in both."""
    a = _write(tmp_path / "a.bin", bytes(range(128, 256)) * 4)
    b = _write(tmp_path / "b.txt", mnemonics[1] + "\n")
    for r in both(c_bin, [a, b]):
        assert r.rc == 3 and r.out == b"", r
        assert ("no share words were found in this file - is it a share "
                "card?") in r.err, r


# ── CRLF, tabs, a UTF-8 BOM ───────────────────────────────────────────


def test_crlf_tabs_and_utf8_bom(c_bin: Path, mnemonics: list[str],
                                tmp_path: Path) -> None:
    a = _write(tmp_path / "a.txt", b"\xef\xbb\xbf"
               + old_card(mnemonics[0]).replace("\n", "\r\n").encode())
    b = _write(tmp_path / "b.txt", mnemonics[1].replace(" ", "\t") + "\r\n")
    assert_password(*both(c_bin, [a, b]))
    bare = _write(tmp_path / "c.txt", b"\xef\xbb\xbf" + mnemonics[2].encode() + b"\n")
    assert_password(*both(c_bin, [a, bare]))


def test_cards_from_password_split_combine_as_printed(
        c_bin: Path, tmp_path: Path) -> None:
    """The card files ``lcsas password split`` writes, as they are."""
    pw = tmp_path / "pw"
    pw.write_bytes(PASSWORD)
    out = tmp_path / "shares"
    assert cli_main([
        "password", "split", "--repo", "alpha", "--threshold", "2",
        "--shares", "3", "--password-file", str(pw), "--out", str(out),
        "--no-verify-repo",
    ]) == 0
    cards = [str(p) for p in sorted(out.glob("alpha-share-*-card.txt"))]
    assert_password(*both(c_bin, [cards[0], cards[2]]))
    piped = b"".join(Path(c).read_bytes() for c in cards[:2])
    assert_password(*both(c_bin, [], stdin=piped))
