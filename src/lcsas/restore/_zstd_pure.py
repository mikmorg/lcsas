"""Pure-Python zstd decompressor — last-resort fallback.

A complete, stdlib-only zstd *decompressor* sufficient to read the
frames that restic / rustic emit (rustic v2 repos are zstd-compressed
by default).  It exists so that tier-3 recovery — the bundled-CPython +
``standalone_restorer.py`` last resort — can decompress repository
blobs decades from now on ANY architecture / CPython minor, with the
``zstandard`` package absent and no stdlib ``compression.zstd`` (which
landed only in CPython 3.14).

**Performance:** Pure-Python entropy decoding is roughly ~1 MB/s — on
par with the pure-Python AES path it sits behind, and acceptable for a
manual emergency restore.  When the ``zstandard`` package IS importable,
``restic_fallback`` uses it instead (~100× faster); this module is the
fallback backend.

Scope (intentionally narrow — decompression only):
    * Single-frame zstd input (the form restic/rustic blobs take).
    * Raw, RLE, and Compressed blocks.
    * Huffman literals (4-stream and single-stream), FSE + repeat /
      RLE / direct literal-length, match-length and offset code modes.
    * Repeat-offset history per RFC 8878 §3.1.1.5.
    * Optional 4-byte XXH64 frame checksum (verified when present).
    * Dictionaries are rejected loudly (restic does not use them).

References:
    * RFC 8878 — Zstandard Compression and the application/zstd Media Type
    * https://github.com/facebook/zstd/blob/dev/doc/zstd_compression_format.md
"""

